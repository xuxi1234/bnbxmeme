import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";
import solc from "solc";
const root = resolve(import.meta.dirname, "..");
const workspace = resolve(root, "../..");
function findImports(path) {
  for (const candidate of [path, path.replace(/^\.\//, "src/")]) {
    try {
      return { contents: readFileSync(resolve(root, candidate), "utf8") };
    } catch {}
  }
  return { error: `Import not found: ${path}` };
}
const entry = "src/BNBXLPRewardsFactory.sol";
const input = {
  language: "Solidity",
  sources: { [entry]: { content: readFileSync(resolve(root, entry), "utf8") } },
  settings: {
    optimizer: { enabled: true, runs: 200 },
    evmVersion: "shanghai",
    outputSelection: {
      "*": {
        "*": ["abi", "evm.bytecode.object", "evm.deployedBytecode.object"],
      },
    },
  },
};
const output = JSON.parse(
  solc.compile(JSON.stringify(input), { import: findImports }),
);
const errors = (output.errors ?? []).filter(
  (item) => item.severity === "error",
);
if (errors.length)
  throw new Error(errors.map((item) => item.formattedMessage).join("\n"));
const factory = output.contracts[entry].BNBXLPRewardsFactory;
const token =
  output.contracts["src/BNBXLPRewardsToken.sol"].BNBXLPRewardsToken;
const runtimeBytes = factory.evm.deployedBytecode.object.length / 2;
const initCodeBytes = factory.evm.bytecode.object.length / 2;
if (runtimeBytes > 24_576)
  throw new Error(`Factory runtime exceeds EIP-170: ${runtimeBytes}`);
if (initCodeBytes > 49_152)
  throw new Error(`Factory init code exceeds EIP-3860: ${initCodeBytes}`);
const lib = resolve(workspace, "apps/web/lib");
mkdirSync(lib, { recursive: true });
writeFileSync(
  resolve(lib, "lp-rewards-factory-deployment.ts"),
  `// Generated by packages/contracts/scripts/export-lp-rewards-web-artifact.mjs.\n` +
    `// Independent lp-rewards Factory artifact; do not edit by hand.\n` +
    `export const lpRewardsFactoryAbi = ${JSON.stringify(factory.abi)} as const;\n` +
    `export const lpRewardsFactoryBytecode = "0x${factory.evm.bytecode.object}" as const;\n`,
);
writeFileSync(
  resolve(lib, "lp-rewards-token-creation-bytecode.ts"),
  `// Generated by packages/contracts/scripts/export-lp-rewards-web-artifact.mjs.\n` +
    `export const lpRewardsTokenAbi = ${JSON.stringify(token.abi)} as const;\n` +
    `export const lpRewardsTokenCreationBytecode = "0x${token.evm.bytecode.object}" as const;\n`,
);
console.log(
  `LP-rewards Factory runtime: ${runtimeBytes} bytes; init code: ${initCodeBytes} bytes`,
);

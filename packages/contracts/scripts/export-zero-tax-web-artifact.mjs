import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";
import solc from "solc";

const root = resolve(import.meta.dirname, "..");
const workspace = resolve(root, "../..");

function findImports(path) {
  const candidates = [path, path.replace(/^\.\//, "src/")];
  for (const candidate of candidates) {
    try {
      return { contents: readFileSync(resolve(root, candidate), "utf8") };
    } catch {
      // Continue.
    }
  }
  return { error: `Import not found: ${path}` };
}

const input = {
  language: "Solidity",
  sources: {
    "src/BNBXZeroTaxFactory.sol": {
      content: readFileSync(
        resolve(root, "src/BNBXZeroTaxFactory.sol"),
        "utf8",
      ),
    },
  },
  settings: {
    optimizer: { enabled: true, runs: 200 },
    evmVersion: "shanghai",
    outputSelection: {
      "*": {
        "*": ["abi", "evm.bytecode.object", "evm.deployedBytecode.object"],
      },
    },
  },
};

const output = JSON.parse(
  solc.compile(JSON.stringify(input), { import: findImports }),
);
const errors = (output.errors ?? []).filter(
  (item) => item.severity === "error",
);
if (errors.length) {
  throw new Error(errors.map((item) => item.formattedMessage).join("\n"));
}

const factory =
  output.contracts["src/BNBXZeroTaxFactory.sol"].BNBXZeroTaxFactory;
const token = output.contracts["src/BNBXZeroTaxToken.sol"].BNBXZeroTaxToken;
const runtimeBytes = factory.evm.deployedBytecode.object.length / 2;
if (runtimeBytes > 24_576) {
  throw new Error(
    `BNBXZeroTaxFactory runtime is ${runtimeBytes} bytes; EIP-170 allows 24576`,
  );
}

const lib = resolve(workspace, "apps/web/lib");
mkdirSync(lib, { recursive: true });
const factoryDestination = resolve(lib, "zero-tax-factory-deployment.ts");
writeFileSync(
  factoryDestination,
  `// Generated by packages/contracts/scripts/export-zero-tax-web-artifact.mjs.\n` +
    `// Dedicated BNBX zero-tax deployment artifact; do not edit by hand.\n` +
    `export const zeroTaxFactoryDeploymentAbi = ${JSON.stringify(factory.abi)} as const;\n` +
    `export const zeroTaxFactoryDeploymentBytecode = "0x${factory.evm.bytecode.object}" as const;\n`,
);

const tokenDestination = resolve(lib, "zero-tax-token-creation-bytecode.ts");
writeFileSync(
  tokenDestination,
  `// Generated by packages/contracts/scripts/export-zero-tax-web-artifact.mjs.\n` +
    `// Used only to audit CREATE2 predictions for the clean zero-tax token.\n` +
    `export const zeroTaxTokenCreationAbi = ${JSON.stringify(token.abi)} as const;\n` +
    `export const zeroTaxTokenCreationBytecode = "0x${token.evm.bytecode.object}" as const;\n`,
);

console.log(`Wrote ${factoryDestination}`);
console.log(`Wrote ${tokenDestination}`);
console.log(`Zero-tax Factory runtime: ${runtimeBytes} bytes`);

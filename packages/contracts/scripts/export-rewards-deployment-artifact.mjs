import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";
import solc from "solc";

const root = resolve(import.meta.dirname, "..");
const workspace = resolve(root, "../..");

function findImports(path) {
  const candidates = [path, path.replace(/^\.\//, "src/")];
  for (const candidate of candidates) {
    try {
      return { contents: readFileSync(resolve(root, candidate), "utf8") };
    } catch {
      // Continue.
    }
  }
  return { error: `Import not found: ${path}` };
}

const sources = [
  "src/BNBXAdvancedTokenDeployer.sol",
  "src/BNBXRewardsFactoryV3.sol",
];
const input = {
  language: "Solidity",
  sources: Object.fromEntries(
    sources.map((path) => [
      path,
      { content: readFileSync(resolve(root, path), "utf8") },
    ]),
  ),
  settings: {
    optimizer: { enabled: true, runs: 200 },
    evmVersion: "shanghai",
    outputSelection: {
      "*": {
        "*": ["abi", "evm.bytecode.object", "evm.deployedBytecode.object"],
      },
    },
  },
};

const output = JSON.parse(
  solc.compile(JSON.stringify(input), { import: findImports }),
);
const errors = (output.errors ?? []).filter(
  (item) => item.severity === "error",
);
if (errors.length) {
  throw new Error(errors.map((item) => item.formattedMessage).join("\n"));
}

const deployer =
  output.contracts["src/BNBXAdvancedTokenDeployer.sol"]
    .BNBXAdvancedTokenDeployer;
const factory =
  output.contracts["src/BNBXRewardsFactoryV3.sol"].BNBXRewardsFactoryV3;
const runtimeBytes = factory.evm.deployedBytecode.object.length / 2;
if (runtimeBytes > 24_576) {
  throw new Error(
    `Advanced factory runtime is ${runtimeBytes} bytes; EIP-170 allows 24576`,
  );
}

const destination = resolve(
  workspace,
  "apps/web/lib/rewards-factory-deployment.ts",
);
mkdirSync(resolve(workspace, "apps/web/lib"), { recursive: true });
writeFileSync(
  destination,
  `// Generated by packages/contracts/scripts/export-rewards-deployment-artifact.mjs.\n` +
    `// BSC deployment artifact; do not edit by hand.\n` +
    `export const advancedTokenDeployerDeploymentAbi = ${JSON.stringify(deployer.abi)} as const;\n` +
    `export const advancedTokenDeployerDeploymentBytecode = "0x${deployer.evm.bytecode.object}" as const;\n` +
    `export const rewardsFactoryDeploymentAbi = ${JSON.stringify(factory.abi)} as const;\n` +
    `export const rewardsFactoryDeploymentBytecode = "0x${factory.evm.bytecode.object}" as const;\n`,
);
console.log(`Wrote ${destination}`);
console.log(`Advanced factory runtime: ${runtimeBytes} bytes`);

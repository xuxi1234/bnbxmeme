import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";
import solc from "solc";

const root = resolve(import.meta.dirname, "..");
const workspace = resolve(root, "../..");

function findImports(path) {
  const candidates = [path, path.replace(/^\.\//, "src/")];
  for (const candidate of candidates) {
    try {
      return { contents: readFileSync(resolve(root, candidate), "utf8") };
    } catch {
      // Continue.
    }
  }
  return { error: `Import not found: ${path}` };
}

const input = {
  language: "Solidity",
  sources: {
    "src/BNBXFactory.sol": {
      content: readFileSync(resolve(root, "src/BNBXFactory.sol"), "utf8"),
    },
    "src/BNBXAutoLiquidityFactory.sol": {
      content: readFileSync(
        resolve(root, "src/BNBXAutoLiquidityFactory.sol"),
        "utf8",
      ),
    },
  },
  settings: {
    // Favor deployable runtime size. Factory contracts embed child creation
    // bytecode and must stay below EIP-170's 24,576-byte runtime limit.
    optimizer: { enabled: true, runs: 200 },
    evmVersion: "shanghai",
    outputSelection: {
      "*": {
        "*": [
          "abi",
          "evm.bytecode.object",
          "evm.deployedBytecode.object",
        ],
      },
    },
  },
};
const output = JSON.parse(solc.compile(JSON.stringify(input), { import: findImports }));
const errors = (output.errors ?? []).filter((item) => item.severity === "error");
if (errors.length) {
  throw new Error(errors.map((item) => item.formattedMessage).join("\n"));
}

const artifact = output.contracts["src/BNBXFactory.sol"].BNBXFactory;
const destination = resolve(workspace, "apps/web/lib/factory-deployment.ts");
mkdirSync(resolve(workspace, "apps/web/lib"), { recursive: true });
writeFileSync(
  destination,
  `// Generated by packages/contracts/scripts/export-web-artifact.mjs.\n` +
    `// Testnet deployment only; do not edit by hand.\n` +
    `export const factoryDeploymentAbi = ${JSON.stringify(artifact.abi)} as const;\n` +
    `export const factoryDeploymentBytecode = "0x${artifact.evm.bytecode.object}" as const;\n`,
);
console.log(`Wrote ${destination}`);

const autoLiquidityArtifact =
  output.contracts["src/BNBXAutoLiquidityFactory.sol"].BNBXAutoLiquidityFactory;
const autoLiquidityRuntimeBytes =
  autoLiquidityArtifact.evm.deployedBytecode.object.length / 2;
if (autoLiquidityRuntimeBytes > 24_576) {
  throw new Error(
    `BNBXAutoLiquidityFactory runtime is ${autoLiquidityRuntimeBytes} bytes; EIP-170 allows 24576`,
  );
}
const autoLiquidityDestination = resolve(
  workspace,
  "apps/web/lib/auto-liquidity-factory-deployment.ts",
);
writeFileSync(
  autoLiquidityDestination,
  `// Generated by packages/contracts/scripts/export-web-artifact.mjs.\n` +
    `// Testnet deployment only; do not edit by hand.\n` +
    `export const autoLiquidityFactoryDeploymentAbi = ${JSON.stringify(autoLiquidityArtifact.abi)} as const;\n` +
    `export const autoLiquidityFactoryDeploymentBytecode = "0x${autoLiquidityArtifact.evm.bytecode.object}" as const;\n`,
);
console.log(`Wrote ${autoLiquidityDestination}`);

import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";
import solc from "solc";

const root = resolve(import.meta.dirname, "..");
const workspace = resolve(root, "../..");

function findImports(path) {
  const candidates = [path, path.replace(/^\.\//, "src/")];
  for (const candidate of candidates) {
    try {
      return { contents: readFileSync(resolve(root, candidate), "utf8") };
    } catch {
      // Continue.
    }
  }
  return { error: `Import not found: ${path}` };
}

const input = {
  language: "Solidity",
  sources: {
    "src/BNBXFactoryV4.sol": {
      content: readFileSync(resolve(root, "src/BNBXFactoryV4.sol"), "utf8"),
    },
  },
  settings: {
    // Favor deployable runtime size. Factory contracts embed child creation
    // bytecode and must stay below EIP-170's 24,576-byte runtime limit.
    optimizer: { enabled: true, runs: 200 },
    evmVersion: "shanghai",
    outputSelection: {
      "*": {
        "*": ["abi", "evm.bytecode.object", "evm.deployedBytecode.object"],
      },
    },
  },
};
const output = JSON.parse(
  solc.compile(JSON.stringify(input), { import: findImports }),
);
const errors = (output.errors ?? []).filter(
  (item) => item.severity === "error",
);
if (errors.length) {
  throw new Error(errors.map((item) => item.formattedMessage).join("\n"));
}

const artifact = output.contracts["src/BNBXFactoryV4.sol"].BNBXFactoryV4;
const runtimeBytes = artifact.evm.deployedBytecode.object.length / 2;
if (runtimeBytes > 24_576) {
  throw new Error(
    `BNBXFactoryV4 runtime is ${runtimeBytes} bytes; EIP-170 allows 24576`,
  );
}
const destination = resolve(workspace, "apps/web/lib/factory-deployment.ts");
mkdirSync(resolve(workspace, "apps/web/lib"), { recursive: true });
writeFileSync(
  destination,
  `// Generated by packages/contracts/scripts/export-web-artifact.mjs.\n` +
    `// BSC deployment artifact; do not edit by hand.\n` +
    `export const factoryDeploymentAbi = ${JSON.stringify(artifact.abi)} as const;\n` +
    `export const factoryDeploymentBytecode = "0x${artifact.evm.bytecode.object}" as const;\n`,
);
console.log(`Wrote ${destination}`);

const standardTokenArtifact =
  output.contracts["src/BNBXTokenV4.sol"].BNBXTokenV4;
const tokenCreationDestination = resolve(
  workspace,
  "apps/web/lib/token-creation-bytecode.ts",
);
writeFileSync(
  tokenCreationDestination,
  `// Generated by packages/contracts/scripts/export-web-artifact.mjs.\n` +
    `// Used only for CREATE2 vanity-address calculation.\n` +
    `export const standardTokenCreationAbi = ${JSON.stringify(standardTokenArtifact.abi)} as const;\n` +
    `export const standardTokenCreationBytecode = "0x${standardTokenArtifact.evm.bytecode.object}" as const;\n`,
);
console.log(`Wrote ${tokenCreationDestination}`);
console.log(`Standard factory runtime: ${runtimeBytes} bytes`);
